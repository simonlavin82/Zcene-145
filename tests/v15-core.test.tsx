import React from 'react';
import { render, screen } from '@testing-library/react';
import { describe, it, expect, vi } from 'vitest';
import { ConsolidatedValidationModal } from '../components/SharedModals';
import { applyShareBlacklistMutation } from '../App';

describe('V15 Core Regression Suite (Integration)', () => {
  it('Validation Lockout: Confirm & Generate is disabled for Unknown Origin artist', () => {
    const mockInvalidSeeds = [
      {
        id: 'seed-1',
        query: 'King of Everything',
        predictedOrigin: 'Unknown Origin',
        isKnownCacheHit: false
      }
    ];

    render(
      <ConsolidatedValidationModal 
        isOpen={true} 
        seeds={mockInvalidSeeds} 
        onConfirm={vi.fn()} 
        onCancel={vi.fn()} 
      />
    );
    
    // Check if the validation origin text renders Unknown Origin
    expect(screen.getByTestId('validation-origin-text')).toHaveTextContent('Unknown Origin');

    // Select the Confirm & Generate button
    const confirmBtn = screen.getByTestId('validation-confirm-button');
    
    // Assert that the button is strictly disabled
    expect(confirmBtn).toBeDisabled();
    expect(confirmBtn).toHaveClass('opacity-50 cursor-not-allowed');
  });

  it('Validation Lockout: Confirm & Generate is enabled for valid origin artist', () => {
    const mockValidSeeds = [
      {
        id: 'seed-2',
        query: 'Nirvana',
        predictedOrigin: 'USA',
        isKnownCacheHit: true
      }
    ];

    render(
      <ConsolidatedValidationModal 
        isOpen={true} 
        seeds={mockValidSeeds} 
        onConfirm={vi.fn()} 
        onCancel={vi.fn()} 
      />
    );

    // Select the Confirm & Generate button
    const confirmBtn = screen.getByTestId('validation-confirm-button');
    
    // Assert that the button is enabled
    expect(confirmBtn).not.toBeDisabled();
  });


  it('Share Payload Blacklist Mutation: Strips coordinates and injects TTL', () => {
    // Utility is imported at top of file

    
    // Mock Base Payload generated by buildBaseProjectPayload
    const basePayload = {
      name: "Mock Project",
      canvasLayout: "[{\"nodeId\":\"artist-1\",\"x\":10,\"y\":20,\"fx\":10,\"fy\":20}]",
      graphData: JSON.stringify({
        nodes: [
          { id: "artist-1", type: "artist", x: 10, y: 20, fx: 10, fy: 20, index: 0 },
          { id: "artist-2", type: "artist", x: 30, y: 40, vx: 1, vy: 1, index: 1 }
        ],
        links: [
          { source: { id: "artist-1" }, target: { id: "artist-2" } }
        ]
      }),
      pinnedNodes: ["artist-1", "artist-2"], // Set serialized to array by base payload
    };

    const sharePayload = applyShareBlacklistMutation(basePayload);

    // 1. Assert TTL
    expect(sharePayload.expireAt).toBeInstanceOf(Date);
    const ttlDiff = sharePayload.expireAt.getTime() - Date.now();
    const days30 = 30 * 24 * 60 * 60 * 1000;
    // Should be roughly 30 days out (allow 1s tolerance)
    expect(Math.abs(ttlDiff - days30)).toBeLessThan(1000);

    // 2. Assert Coordinate Amnesia (canvasLayout stripped)
    expect(sharePayload.canvasLayout).toBeUndefined();

    // 3. Assert Rigid Node Coordinates (fx, fy, x, y, vx, vy, index) stripped from graphData
    const parsedGraph = JSON.parse(sharePayload.graphData);
    expect(parsedGraph.nodes[0]).toEqual({ id: "artist-1", type: "artist" });
    expect(parsedGraph.nodes[1]).toEqual({ id: "artist-2", type: "artist" });

    // Ensure links are also clean
    expect(parsedGraph.links[0]).toEqual({ source: "artist-1", target: "artist-2" });

    // 4. Assert Pinned Nodes
    expect(Array.isArray(sharePayload.pinnedNodes)).toBe(true);
    expect(sharePayload.pinnedNodes).toEqual(["artist-1", "artist-2"]);
  });
});
