const makeCuratedScene = (opts: {
  idx: number;
  seedName: string;
  seedCanonId: string;
  peerName: string;
  peerCanonId: string;
  customName?: string;
  zineTitle?: string;
  zineIntro?: string;
  zineImages?: any[];
  sharedPeer?: { name: string; canonId: string };
  discoveryFilters?: Record<string, any>;
}): ProjectScene => {
  const sceneId = `scene-${opts.idx + 1}`;
  const cx = 1000 + opts.idx * SCENE_HORIZONTAL_STRIDE;
  const cy = 1000;
  const nodes: any[] = [
    {
      id: `${sceneId}::${opts.seedCanonId}`,
      canonicalId: opts.seedCanonId,
      sceneId,
      sceneIndex: opts.idx,
      label: opts.seedName,
      type: 'artist',
      group: 0,
      isSeed: true,
      isSceneSeed: true,
      x: cx,
      y: cy,
      fx: cx,
      fy: cy,
    },
    {
      id: `${sceneId}::${opts.peerCanonId}`,
      canonicalId: opts.peerCanonId,
      sceneId,
      sceneIndex: opts.idx,
      label: opts.peerName,
      type: 'artist',
      group: 1,
      x: cx + 140,
      y: cy - 90,
      fx: cx + 140,
      fy: cy - 90,
    },
  ];
  const links: any[] = [
    {
      source: `${sceneId}::${opts.seedCanonId}`,
      target: `${sceneId}::${opts.peerCanonId}`,
      value: 1,
      weight: 0.85,
      sceneId,
    },
  ];

  if (opts.sharedPeer) {
    nodes.push({
      id: `${sceneId}::${opts.sharedPeer.canonId}`,
      canonicalId: opts.sharedPeer.canonId,
      sceneId,
      sceneIndex: opts.idx,
      label: opts.sharedPeer.name,
      type: 'artist',
      group: 1,
      x: cx - 150,
      y: cy + 110,
      fx: cx - 150,
      fy: cy + 110,
    });
    links.push({
      source: `${sceneId}::${opts.seedCanonId}`,
      target: `${sceneId}::${opts.sharedPeer.canonId}`,
      value: 1,
      weight: 0.65,
      sceneId,
    });
  }

  return {
    id: sceneId,
    sceneId,
    sceneIndex: opts.idx,
    title: opts.customName || opts.seedName,
    name: opts.customName || opts.seedName,
    ...(opts.customName ? { customName: opts.customName } : {}),
    seedArtists: opts.seedName,
    curatedSeedArtists: opts.seedName,
    seedIds: [opts.seedCanonId],
    seedArtistIds: [opts.seedCanonId],
    discoveryFilters: (opts.discoveryFilters || {}) as any,
    curatedDiscoveryFilters: (opts.discoveryFilters || {}) as any,
    graphData: {
      nodes,
      links,
      synthesisRationale: `Deep archival notes anchoring ${opts.seedName} and ${opts.peerName} inside their scene.`,
    },
    synthesisRationale: `Deep archival notes anchoring ${opts.seedName} and ${opts.peerName} inside their scene.`,
    ...(opts.zineTitle ? { zineTitle: opts.zineTitle } : {}),
    ...(opts.zineIntro ? { zineIntro: opts.zineIntro } : {}),
    ...(opts.zineImages ? { zineImages: opts.zineImages } : {}),
    centerOffset: { x: cx, y: cy },
    status: 'completed',
    updatedAt: 1700000000000 + opts.idx * 1000,
  };
};

